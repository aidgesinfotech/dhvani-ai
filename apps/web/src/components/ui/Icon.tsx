export const ICON_NAMES = Object.keys(MAP).sort();

export function Icon({ name, ...props }: { name?: string } & LucideProps) {
  const Cmp = (name && MAP[name.toLowerCase().trim()]) || Sparkles;
  return <Cmp strokeWidth={1.75} {...props} />;
}
